#!/usr/bin/env bash
# Writes docs/notices.md: every Go module linked into the pgvigil binary with its licence, from
# go-licenses (google/go-licenses v1.6.0, confidence 0.9) over ./cmd/pgvigil. Run it after a go.mod change
# and commit the result; the frontend's dependencies (uPlot; pev2 with vue, bootstrap's CSS and
# fontawesome's styles for the Plan page) are listed at the end from web/package.json and web/node_modules. THIRD-PARTY-NOTICES.md stays the file for borrowed CODE and ideas (queries, rules,
# designs); this one is the binary's module inventory for a software review.
set -euo pipefail
cd "$(dirname "$0")/.."
GOBIN_DIR=$(go env GOBIN); [[ -n "$GOBIN_DIR" ]] || GOBIN_DIR=$(go env GOPATH)/bin
[[ -x "$GOBIN_DIR/go-licenses" ]] || go install github.com/google/go-licenses@v1.6.0
TMP=$(mktemp); trap 'rm -f "$TMP"' EXIT
"$GOBIN_DIR/go-licenses" report ./cmd/pgvigil 2>/dev/null | sort > "$TMP"
UPLOT=$(sed -n 's/.*"uplot": *"\([^"]*\)".*/\1/p' web/package.json)
ver() { sed -n 's/.*"version": *"\([^"]*\)".*/\1/p' "web/node_modules/$1/package.json" | head -1; }   # the installed version of a web package
PEV2=$(ver pev2); VUE=$(ver vue); BOOTSTRAP=$(ver bootstrap); FA=$(ver @fortawesome/fontawesome-svg-core)
{
  echo "# Third-party modules in the pgvigil binary"
  echo
  echo "Every Go module linked into \`pgvigil\` (\`./cmd/pgvigil\`), and every package of one that carries a licence file of its own, with the licence go-licenses detected in its source, generated by \`scripts/notices.sh\` on $(date -u +%Y-%m-%d) from \`go.mod\` at $(git rev-parse --short HEAD). The licences in use are MIT, Apache-2.0, BSD-2-Clause, BSD-3-Clause, and MPL-2.0 (hashicorp/go-uuid through the Kerberos client, used unmodified: MPL-2.0 is file-level copyleft; where its source is, below). The SBOM attached to every release (\`*.cdx.json\`, CycloneDX 1.6) carries the same modules with their versions and purls for an automated review. Borrowed code and ideas (queries, rules, designs from other tools) are listed in [THIRD-PARTY-NOTICES.md](../THIRD-PARTY-NOTICES.md), not here."
  echo
  echo "| Module | Licence | Licence file |"
  echo "|---|---|---|"
  while IFS=, read -r mod url lic; do
    [[ "$mod" == "github.com/aachaemenes/pgvigil" ]] && continue
    echo "| \`$mod\` | $lic | [$(basename "$url")]($url) |"
  done < "$TMP"
  # MPL-2.0 section 3.2(a): an executable form tells its recipients how to obtain the covered files' source - the
  # module, its exact version, and that version's source archive on the Go module proxy (scripts/proof-sbom.sh checks it)
  MPL=$(awk -F, '$3 == "MPL-2.0" {print $1}' "$TMP")
  if [[ -n "$MPL" ]]; then
    echo
    echo "## Source of the MPL-2.0 modules"
    echo
    echo "These files are used unmodified; their source, at the exact version linked:"
    echo
    for pkg in $MPL; do go list -f '{{.Module.Path}} {{.Module.Version}}' "$pkg"; done | sort -u | while read -r mp mv; do
      esc=$(sed 's/[A-Z]/!\L&/g' <<<"$mp")   # the proxy's case encoding
      echo "- \`$mp@$mv\`: <https://proxy.golang.org/$esc/@v/$mv.zip>"
    done
  fi
  # BSD-2-Clause asks that a binary's documentation reproduce the copyright notice: each such module's lines, from its
  # own licence file at the version linked
  BSD2=$(awk -F, '$3 == "BSD-2-Clause" {print $1}' "$TMP")
  if [[ -n "$BSD2" ]]; then
    echo
    echo "## Copyright notices of the BSD-2-Clause modules"
    echo
    for pkg in $BSD2; do go list -f '{{.Module.Path}} {{.Module.Version}} {{.Module.Dir}}' "$pkg"; done | sort -u | while read -r mp mv md; do
      echo "- \`$mp@$mv\`: $(grep -ihE '^ *copyright' "$md"/LICENSE* | sed 's/^ *//' | paste -sd ';' -) (BSD-2-Clause, its licence file linked above)"
    done
  fi
  echo
  echo "## The web UI"
  echo
  echo "| Package | Version | Licence |"
  echo "|---|---|---|"
  echo "| \`uplot\` (bundled into \`internal/web/dist/app.js\`) | $UPLOT | MIT |"
  echo "| \`pev2\` (the plan viewer, bundled into \`internal/web/dist/pev2/pev2.js\`, loaded only on the Plan page; its own bundle's parts are listed in THIRD-PARTY-NOTICES.md) | $PEV2 | PostgreSQL |"
  echo "| \`vue\` (pev2's framework, \`internal/web/dist/pev2/vue.js\`) | $VUE | MIT |"
  echo "| \`bootstrap\` (CSS only, inside the viewer's shadow root, \`internal/web/dist/pev2/bootstrap.min.css\`) | $BOOTSTRAP | MIT |"
  echo "| \`@fortawesome/fontawesome-svg-core\` (styles.css as \`internal/web/dist/pev2/fontawesome.css\`) | $FA | MIT |"
  echo
  echo "pgvigil itself is MIT ([LICENSE](../LICENSE))."
} > docs/notices.md
echo "wrote docs/notices.md ($(grep -c '^| `' docs/notices.md) rows)"
